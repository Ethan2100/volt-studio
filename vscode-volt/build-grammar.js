#!/usr/bin/env node
// Builds syntaxes/volt.tmLanguage.json from the compiler's own word lists, so VS Code colours
// exactly the words Volt actually has. Run it after adding a built-in:
//
//   node vscode-volt/build-grammar.js
//
// test/suite/13-vscode.js checks the committed file matches what this produces.
const fs = require('fs');
const path = require('path');
const ls = require(path.join(__dirname, '..', 'lib', 'language-service.js'));
const volt = require(path.join(__dirname, '..', 'compiler', 'volt.js'));
const plugins = require(path.join(__dirname, '..', 'lib', 'plugins.js'));

// The bundled addon targets (#lua, #luau, #pseudo) ship with Volt Studio, so their first lines
// belong in the grammar too. Loading them here also makes this script produce the same file
// however it is run.
try {
  plugins.loadTargetPlugins(plugins.scanPlugins(path.join(__dirname, '..', 'plugins'), path.join(__dirname, '..', '.no-user-plugins')), volt, null);
} catch (e) { /* no plugins: just the built-in targets */ }

function build() {
  const w = ls.highlightWords();
  const any = (list) => list.map((x) => x.replace(/[+*?.^$()[\]{}|\\]/g, '\\$&')).join('|');
  return {
    $schema: 'https://raw.githubusercontent.com/martinring/tmlanguage/master/tmlanguage.json',
    name: 'Volt',
    scopeName: 'source.volt',
    // Generated by vscode-volt/build-grammar.js - do not edit by hand.
    patterns: [
      { include: '#comment' },
      { include: '#target' },
      { include: '#raw' },
      { include: '#string' },
      { include: '#number' },
      { include: '#type' },
      { include: '#function' },
      { include: '#keyword' },
      { include: '#command' },
      { include: '#builtin' },
      { include: '#operator' },
    ],
    repository: {
      comment: { match: '//.*$', name: 'comment.line.double-slash.volt' },
      // the first line picks the language: #html, #c++ ...
      target: { match: `^\\s*#(?:${any(w.targets)})\\s*$`, name: 'keyword.control.directive.volt' },
      // a # line is raw code in the output language, ## goes at the top of the file
      raw: { match: '^\\s*#.*$', name: 'meta.embedded.volt' },
      string: {
        name: 'string.quoted.double.volt',
        begin: '"',
        end: '"',
        patterns: [
          { match: '\\\\.', name: 'constant.character.escape.volt' },
          // "{hp}" puts a value inside text
          { begin: '\\{', end: '\\}', name: 'meta.interpolation.volt', patterns: [{ include: '$self' }] },
        ],
      },
      number: { match: '\\b\\d+(?:\\.\\d+)?(?:ms|s)?\\b', name: 'constant.numeric.volt' },
      type: { match: '\\b([A-Za-z_]\\w*)(?=\\s*=\\s*type\\b)', name: 'entity.name.type.volt' },
      function: { match: '(?<=\\bfn\\s)\\s*[A-Za-z_]\\w*', name: 'entity.name.function.volt' },
      keyword: { match: `\\b(?:${any(w.keywords)})\\b`, name: 'keyword.control.volt' },
      command: { match: `^\\s*(?:${any(w.commands)})\\b`, name: 'support.function.command.volt' },
      builtin: { match: `\\b(?:${any(w.builtins)})(?=\\s*\\()`, name: 'support.function.builtin.volt' },
      operator: { match: '\\+\\+|--|[-+*/%]=|[=!<>]=|[-+*/%=<>]', name: 'keyword.operator.volt' },
    },
  };
}

const out = path.join(__dirname, 'syntaxes', 'volt.tmLanguage.json');
if (require.main === module) {
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, `${JSON.stringify(build(), null, 2)}\n`);
  console.log(`Wrote ${path.relative(process.cwd(), out)}`);
}
module.exports = { build, out };
