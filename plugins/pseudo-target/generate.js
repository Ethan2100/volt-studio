// =====================================================================
// #pseudo target addon - turns a parsed Volt program into plain-English
// pseudocode, for explaining a sketch to someone who doesn't read code.
//
// This is an example of a "target" addon: it is handed Volt's own real
// parsed AST (the same tree the built-in C++/Python/etc generators work
// from - see compiler/volt.js's node `kind`s) and returns a string. It
// never touches Volt's lexer/parser or the built-in generate() function;
// Volt Studio's plugin loader registers it against the first-line word
// "#pseudo" via volt.registerTarget().
// =====================================================================

function expr(n) {
  if (!n) return '';
  switch (n.kind) {
    case 'Number': return n.value;
    case 'String': return `"${n.value}"`;
    case 'Bool': return n.value ? 'true' : 'false';
    case 'Var': return n.name;
    case 'Uptime': return 'the time since start';
    case 'Ask': return `the answer to ${expr(n.prompt)}`;
    case 'Read': return `the reading on pin ${n.pin}`;
    case 'Call': return `${n.name}(${(n.args || []).map(expr).join(', ')})`;
    case 'Unary': return `${n.op}${expr(n.operand)}`;
    case 'Binary': {
      const OPS = { '+': 'plus', '-': 'minus', '*': 'times', '/': 'divided by', '%': 'mod',
        '==': 'equals', '!=': 'does not equal', '<': 'is less than', '>': 'is greater than',
        '<=': 'is at most', '>=': 'is at least', '&&': 'and', '||': 'or' };
      return `${expr(n.left)} ${OPS[n.op] || n.op} ${expr(n.right)}`;
    }
    default: return `<${n.kind}>`;
  }
}

function block(stmts, depth) {
  return stmts.map((s) => line(s, depth)).join('\n');
}

function pad(depth) { return '  '.repeat(depth); }

function line(n, depth) {
  const p = pad(depth);
  switch (n.kind) {
    case 'Let':
      return `${p}${n.topLevel ? 'Remember' : 'Set'} ${n.name} = ${expr(n.value)}`;
    case 'Assign':
      return `${p}Update ${n.name} = ${expr(n.value)}`;
    case 'Fn':
      return `${p}To ${n.name}(${(n.params || []).join(', ')}):\n${block(n.body, depth + 1)}`;
    case 'Return':
      return `${p}Give back ${n.value ? expr(n.value) : '(nothing)'}`;
    case 'Forever':
      return `${p}Repeat forever:\n${block(n.body, depth + 1)}`;
    case 'Every':
      return `${p}Every ${n.ms} ms:\n${block(n.body, depth + 1)}`;
    case 'When':
      return `${p}Whenever pin ${n.pin} changes:\n${block(n.body, depth + 1)}`;
    case 'WhenKey':
      return `${p}Whenever the "${n.key}" key is pressed:\n${block(n.body, depth + 1)}`;
    case 'Write': {
      const VERB = { on: 'Turn on', off: 'Turn off', toggle: 'Toggle' };
      return `${p}${VERB[n.action] || n.action} pin ${n.pin}`;
    }
    case 'SetSpeed':
      return `${p}Set pin ${n.pin}'s speed to ${expr(n.value)}`;
    case 'Set':
      return `${p}Set pin ${n.pin} to ${expr(n.value)}`;
    case 'Fade':
      return `${p}Fade pin ${n.pin} to ${expr(n.value)} over ${expr(n.time)} ms`;
    case 'Tone':
      return `${p}Play ${expr(n.freq)} Hz on pin ${n.pin}${n.time ? ` for ${expr(n.time)} ms` : ''}`;
    case 'Wait':
      return `${p}Wait ${expr(n.time)} ms`;
    case 'Print':
      return `${p}Say ${expr(n.value)}`;
    case 'Show':
      return `${p}Display ${expr(n.value)}`;
    case 'Clear':
      return `${p}Clear the screen`;
    case 'Stop':
      return `${p}Stop the program`;
    case 'If':
      return `${p}If ${expr(n.cond)}:\n${block(n.then, depth + 1)}` +
        (n.otherwise ? `\n${p}Otherwise:\n${block(n.otherwise, depth + 1)}` : '');
    case 'For':
      return `${p}For ${n.name} from ${expr(n.start)} to ${expr(n.end)}:\n${block(n.body, depth + 1)}`;
    case 'Repeat':
      return `${p}Repeat ${expr(n.count)} times:\n${block(n.body, depth + 1)}`;
    case 'While':
      return `${p}While ${expr(n.cond)}:\n${block(n.body, depth + 1)}`;
    case 'Break':
      return `${p}Break out of the loop`;
    case 'Button':
      return `${p}When the ${expr(n.label)} button is pressed:\n${block(n.body, depth + 1)}`;
    case 'CallStmt':
      return `${p}${expr(n.call)}`;
    case 'Raw':
    case 'RawTop':
      return `${p}(runs this code directly: ${n.code.trim().split('\n')[0]}${n.code.includes('\n') ? ' ...' : ''})`;
    case 'Pin':
      return `${p}Pin ${n.name} is ${n.mode || 'pin'} ${n.num}`;
    case 'Title':
      return `${p}Set the page title to ${expr(n.value)}`;
    case 'Html':
      return `${p}Insert this HTML: ${expr(n.value)}`;
    default:
      return `${p}(${n.kind})`;
  }
}

function generate(ast) {
  const header = [
    '# What this program does, in plain English',
    '# (generated by the #pseudo target addon - not meant to run)',
    '',
  ].join('\n');
  return header + block(ast, 0) + '\n';
}

module.exports = { generate };
